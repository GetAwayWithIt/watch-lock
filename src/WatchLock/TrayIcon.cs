using System.Runtime.InteropServices;
using System.Windows.Interop;
using static WatchLock.NativeMethods;

namespace WatchLock;

/// <summary>
/// System tray icon + global hotkey. Built directly on Win32 instead of WinForms to keep memory low.
/// </summary>
public sealed class TrayIcon : IDisposable
{
    private const uint WM_TRAY = 0x8000 + 1; // WM_APP + 1
    private const int WM_LBUTTONUP = 0x0202, WM_RBUTTONUP = 0x0205;
    private const int MENU_OPEN = 1, MENU_LOCK = 2, MENU_EXIT = 3;

    private readonly HwndSource _window;
    private readonly uint _taskbarCreated;
    private IntPtr _icon;
    private bool _locked;

    // Ctrl+AltGr+F: Windows sends AltGr as "fake Left Ctrl + Right Alt", so RegisterHotKey can't tell
    // AltGr+F from Ctrl+AltGr+F. We track the keys ourselves with a low-level hook instead.
    private readonly HookProc _keyboardProc;
    private IntPtr _keyboardHook;
    private bool _leftCtrl, _rightCtrl, _altGr, _swallowedF;
    private bool _leftCtrlBefore;
    private uint _leftCtrlTime;

    public event Action? OpenRequested;
    public event Action? LockRequested;
    public event Action? ExitRequested;

    public bool HotkeyActive { get; }

    public TrayIcon()
    {
        // Invisible top-level window that receives tray messages.
        _window = new HwndSource(new HwndSourceParameters("WatchLockTray") { Width = 0, Height = 0, WindowStyle = 0 });
        _window.AddHook(WndProc);
        _taskbarCreated = RegisterWindowMessage("TaskbarCreated");

        var small = new IntPtr[1];
        if (Environment.ProcessPath is { } path && ExtractIconEx(path, 0, null, small, 1) > 0 && small[0] != IntPtr.Zero)
            _icon = small[0];
        else
            _icon = LoadIcon(IntPtr.Zero, new IntPtr(32512)); // IDI_APPLICATION

        Add();
        _keyboardProc = KeyboardHook;
        _keyboardHook = SetWindowsHookEx(WH_KEYBOARD_LL, _keyboardProc, GetModuleHandle(null), 0);
        HotkeyActive = _keyboardHook != IntPtr.Zero;
    }

    public bool Locked
    {
        get => _locked;
        set { _locked = value; RefreshTooltip(); }
    }

    // ---------------- Hotkey ----------------

    private const int VK_F = 0x46, VK_LCONTROL = 0xA2, VK_RCONTROL = 0xA3, VK_RMENU = 0xA5;

    private IntPtr KeyboardHook(int nCode, IntPtr wParam, IntPtr lParam)
    {
        if (nCode >= 0)
        {
            var k = Marshal.PtrToStructure<KBDLLHOOKSTRUCT>(lParam);
            bool down = (k.flags & LLKHF_UP) == 0;
            switch ((int)k.vkCode)
            {
                case VK_LCONTROL:
                    // The fake Ctrl generated by AltGr has bit 0x200 set in its scan code; ignore it.
                    if ((k.scanCode & 0x200) == 0)
                    {
                        if (down) { _leftCtrlBefore = _leftCtrl; _leftCtrlTime = k.time; }
                        _leftCtrl = down;
                    }
                    break;
                case VK_RCONTROL:
                    _rightCtrl = down;
                    break;
                case VK_RMENU:
                    // Backup check: the fake Ctrl arrives with the same timestamp as AltGr.
                    if (down && k.time == _leftCtrlTime) _leftCtrl = _leftCtrlBefore;
                    _altGr = down;
                    break;
                case VK_F:
                    if (down && !_locked && HotkeyPressed())
                    {
                        _swallowedF = true;
                        _window.Dispatcher.BeginInvoke(() => LockRequested?.Invoke());
                        return 1; // don't let the "F" reach the focused app
                    }
                    if (!down && _swallowedF) { _swallowedF = false; return 1; }
                    break;
            }
        }
        return CallNextHookEx(_keyboardHook, nCode, wParam, lParam);
    }

    private bool HotkeyPressed()
    {
        // Double-check our tracked state against the real key state in case we missed an event.
        bool altGr = _altGr && GetAsyncKeyState(VK_RMENU) < 0;
        bool ctrl = (_rightCtrl && GetAsyncKeyState(VK_RCONTROL) < 0)
                 || (_leftCtrl && GetAsyncKeyState(VK_LCONTROL) < 0);
        return altGr && ctrl;
    }

    // ---------------- Tray icon ----------------

    private NOTIFYICONDATA Data(uint flags) => new()
    {
        cbSize = Marshal.SizeOf<NOTIFYICONDATA>(),
        hWnd = _window.Handle,
        uID = 1,
        uFlags = flags,
        uCallbackMessage = WM_TRAY,
        hIcon = _icon,
        szTip = _locked ? Strings.TrayTipLocked : Strings.TrayTipUnlocked,
        szInfo = "",
        szInfoTitle = "",
    };

    private void Add()
    {
        var d = Data(NIF_MESSAGE | NIF_ICON | NIF_TIP);
        Shell_NotifyIcon(NIM_ADD, ref d);
    }

    /// <summary>Also called after the language changes.</summary>
    public void RefreshTooltip()
    {
        var d = Data(NIF_TIP);
        Shell_NotifyIcon(NIM_MODIFY, ref d);
    }

    /// <summary>Shows a small notification from the tray icon.</summary>
    public void Notify(string title, string text)
    {
        var d = Data(NIF_INFO);
        d.szInfoTitle = title;
        d.szInfo = text;
        d.dwInfoFlags = NIIF_USER;
        Shell_NotifyIcon(NIM_MODIFY, ref d);
    }

    private IntPtr WndProc(IntPtr hwnd, int msg, IntPtr wParam, IntPtr lParam, ref bool handled)
    {
        if (msg == WM_TRAY)
        {
            handled = true;
            if (_locked) return IntPtr.Zero; // the tray menu must not work while locked
            int mouse = lParam.ToInt32() & 0xFFFF;
            if (mouse == WM_LBUTTONUP) OpenRequested?.Invoke();
            else if (mouse == WM_RBUTTONUP) ShowMenu();
        }
        else if (msg == (int)_taskbarCreated)
        {
            Add(); // Explorer restarted: put the icon back
        }
        return IntPtr.Zero;
    }

    private void ShowMenu()
    {
        IntPtr menu = CreatePopupMenu();
        AppendMenu(menu, MF_STRING, (UIntPtr)MENU_OPEN, Strings.MenuOpen);
        AppendMenu(menu, MF_STRING, (UIntPtr)MENU_LOCK, $"{Strings.MenuLock}\t{Strings.HotkeyText}");
        AppendMenu(menu, MF_SEPARATOR, UIntPtr.Zero, null);
        AppendMenu(menu, MF_STRING, (UIntPtr)MENU_EXIT, Strings.MenuExit);

        GetCursorPos(out var p);
        SetForegroundWindow(_window.Handle); // needed so the menu closes when clicking elsewhere
        int choice = TrackPopupMenu(menu, TPM_RETURNCMD | TPM_RIGHTBUTTON | TPM_BOTTOMALIGN, p.X, p.Y, 0, _window.Handle, IntPtr.Zero);
        PostMessage(_window.Handle, 0, IntPtr.Zero, IntPtr.Zero);
        DestroyMenu(menu);

        switch (choice)
        {
            case MENU_OPEN: OpenRequested?.Invoke(); break;
            case MENU_LOCK: LockRequested?.Invoke(); break;
            case MENU_EXIT: ExitRequested?.Invoke(); break;
        }
    }

    public void Dispose()
    {
        if (_keyboardHook != IntPtr.Zero) UnhookWindowsHookEx(_keyboardHook);
        _keyboardHook = IntPtr.Zero;
        var d = Data(0);
        Shell_NotifyIcon(NIM_DELETE, ref d);
        if (_icon != IntPtr.Zero) DestroyIcon(_icon);
        _icon = IntPtr.Zero;
        _window.Dispose();
    }
}
